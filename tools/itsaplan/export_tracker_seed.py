#!/usr/bin/env python3
"""Regenerates tracker/seed/jgy-seed.sql from a running It's a Plan instance.

This is a maintenance tool (run by hand when the JGY backlog changes), not part
of the app. It exports exactly the JGY project's rows (never other projects),
rewrites the account into a documented sandbox login, and mints a known sandbox
API key, so `docker compose -f tracker/docker-compose.yml up -d` reproduces the
same work items on a fresh volume.

Usage:
    python tools/itsaplan/export_tracker_seed.py            # against the local stack
    TRACKER_PG_CONTAINER=itsaplan-postgres-1 ...            # override container

Requirements: the tracker's postgres container must be reachable via `docker exec`.
"""
from __future__ import annotations

import base64
import hashlib
import os
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "tracker" / "seed" / "jgy-seed.sql"

PG = os.environ.get("TRACKER_PG_CONTAINER", "itsaplan-postgres-1")
PGUSER = os.environ.get("TRACKER_PG_USER", "itsaplan")
PGDB = os.environ.get("TRACKER_PG_DB", "itsaplan")

PROJECT_KEY = "JGY"

# Sandbox identity written into the seed (documented in tracker/README.md).
SANDBOX_EMAIL = "admin@jegyzo.local"
SANDBOX_NAME = "Jegyzo Admin"
SANDBOX_PASSWORD = "Jegyzo1234"
SANDBOX_API_KEY = "itp_jegyzoSandboxKey000000000000000000000000000000000000000000000000"


def psql(sql: str) -> str:
    r = subprocess.run(
        ["docker", "exec", PG, "psql", "-U", PGUSER, "-d", PGDB, "-v", "ON_ERROR_STOP=1", "-tAc", sql],
        capture_output=True, text=True,
    )
    if r.returncode != 0:
        sys.exit(f"psql failed: {r.stderr.strip()}")
    return r.stdout.strip()


def copy_out(table: str, where: str | None) -> str:
    sql = f"COPY (SELECT * FROM {table}{' WHERE ' + where if where else ''}) TO STDOUT"
    r = subprocess.run(
        ["docker", "exec", PG, "psql", "-U", PGUSER, "-d", PGDB, "-c", sql],
        capture_output=True, text=True,
    )
    if r.returncode != 0:
        sys.exit(f"COPY {table} failed: {r.stderr.strip()}")
    return r.stdout


def sql_str(v: str | None) -> str:
    if v is None:
        return "NULL"
    return "'" + v.replace("'", "''") + "'"


def api_key_hash(plaintext: str) -> str:
    return base64.urlsafe_b64encode(hashlib.sha256(plaintext.encode()).digest()).decode().rstrip("=")


def scrypt_password(password: str) -> str:
    """better-auth credential format: <salt_hex>:<hash_hex>.

    Matches @better-auth/utils: scrypt(N=16384, r=16, p=1, dkLen=64) where the
    salt is the *hex string's* UTF-8 bytes (Node passes the string through).
    """
    salt = os.urandom(16).hex()
    dk = hashlib.scrypt(
        password.encode(), salt=salt.encode(), n=16384, r=16, p=1, dklen=64,
        maxmem=128 * 16384 * 16 * 2,
    )
    return f"{salt}:{dk.hex()}"


def main() -> None:
    pid = psql(f"select id from project where key = '{PROJECT_KEY}'")
    if not pid:
        sys.exit(f"project {PROJECT_KEY} not found in {PG}")
    pid = int(pid)
    in_jgy = f"project_id = {pid}"
    issue_ids = f"(select id from issue where {in_jgy})"

    uid = psql(f"select user_id from project_member where project_id = {pid} limit 1")
    uname = psql(f"select name from \"user\" where id = {sql_str(uid)}")
    account = psql(
        f"select id, account_id, provider_id, created_at, updated_at from account "
        f"where user_id = {sql_str(uid)} limit 1")
    acc_id, acc_account, acc_provider, acc_created, acc_updated = account.split("|")

    parts: list[str] = []
    parts.append(f"""-- Jegyzo — It's a Plan (tracker) seed data
-- Generated by tools/itsaplan/export_tracker_seed.py from a running instance.
-- Contains ONLY the {PROJECT_KEY} project. Loaded by tracker/seed/seed.sh when the
-- {PROJECT_KEY} project is absent. Schema must come from the migrate service first.

SET session_replication_role = replica;  -- load parents/children without FK ordering
BEGIN;
""")

    # --- sandbox identity -------------------------------------------------
    parts.append("-- Account (sandbox login, password: %s)\n" % SANDBOX_PASSWORD)
    parts.append(
        f"INSERT INTO \"user\" (id, name, email, email_verified, created_at, updated_at) "
        f"SELECT {sql_str(uid)}, {sql_str(SANDBOX_NAME)}, {sql_str(SANDBOX_EMAIL)}, true, "
        f"COALESCE((SELECT created_at FROM \"user\" WHERE id = {sql_str(uid)}), now()), now() "
        f"WHERE NOT EXISTS (SELECT 1 FROM \"user\" WHERE id = {sql_str(uid)});\n"
    )
    pw = scrypt_password(SANDBOX_PASSWORD)
    parts.append(
        f"DELETE FROM account WHERE user_id = {sql_str(uid)} AND provider_id = 'credential';\n"
        f"INSERT INTO account (id, account_id, provider_id, user_id, password, created_at, updated_at) VALUES ("
        f"{sql_str(acc_id)}, {sql_str(uid)}, 'credential', {sql_str(uid)}, {sql_str(pw)}, "
        f"{sql_str(acc_created)}, {sql_str(acc_updated)});\n"
    )
    parts.append(f"-- API key (plaintext: {SANDBOX_API_KEY})\n")
    parts.append(
        f"DELETE FROM apikey WHERE reference_id = {sql_str(uid)};\n"
        f"INSERT INTO apikey (id, config_id, name, start, reference_id, prefix, key, enabled, "
        f"rate_limit_enabled, request_count, remaining, created_at, updated_at) VALUES ("
        f"gen_random_uuid()::text, 'default', 'Jegyzo sandbox', {sql_str(SANDBOX_API_KEY[:6])}, "
        f"{sql_str(uid)}, 'itp_', {sql_str(api_key_hash(SANDBOX_API_KEY))}, true, false, 0, NULL, "
        f"now(), now());\n"
    )

    # --- team + project graph --------------------------------------------
    ops = [
        ("team", f"id = (select team_id from project where id = {pid})"),
        ("team_role", f"team_id = (select team_id from project where id = {pid})"),
        ("team_member", f"team_id = (select team_id from project where id = {pid})"),
        ("project", f"id = {pid}"),
        ("project_column", in_jgy),
        ("issue_type", in_jgy),
        ("label_group", in_jgy),
        ("label", in_jgy),
        ("project_setting", in_jgy),
        ("project_member", in_jgy),
        ("issue", in_jgy),
        ("issue_link", f"source_issue_id in {issue_ids} and target_issue_id in {issue_ids}"),
        ("issue_label", f"issue_id in {issue_ids}"),
        ("issue_checklist", f"issue_id in {issue_ids}"),
        ("issue_checklist_item", f"checklist_id in (select id from issue_checklist where issue_id in {issue_ids})"),
    ]
    for table, where in ops:
        data = copy_out(table, where)
        if not data.strip():
            continue
        parts.append(f"\n-- {table} ({len(data.strip().splitlines())} rows)\nCOPY {table} FROM STDIN;\n")
        parts.append(data if data.endswith("\n") else data + "\n")
        parts.append("\\.\n")

    # --- sequence fixups --------------------------------------------------
    seq_tables = ["team", "team_role", "project", "project_column", "issue_type",
                  "label_group", "label", "issue", "issue_link", "issue_checklist",
                  "issue_checklist_item"]
    parts.append("\n-- keep sequences ahead of the imported rows\n")
    for t in seq_tables:
        col = psql(
            "select column_name from information_schema.columns "
            "where table_name = '" + t + "' and column_default like 'nextval%' limit 1")
        if col:
            parts.append(
                f"SELECT setval(pg_get_serial_sequence('{t}', '{col}'), "
                f"COALESCE((SELECT max({col}) FROM {t}), 1));\n")
    parts.append(
        f"SELECT setval(pg_get_serial_sequence('project', 'next_sequence'), "
        f"GREATEST((SELECT max(sequence_number) FROM issue WHERE project_id = {pid}), 1));\n"
    )

    parts.append("COMMIT;\nSET session_replication_role = DEFAULT;\n")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("".join(parts), encoding="utf-8")
    size = OUT.stat().st_size
    print(f"wrote {OUT} ({size/1024:.1f} KB) for project {PROJECT_KEY} (id={pid})")
    print(f"sandbox login: {SANDBOX_EMAIL} / {SANDBOX_PASSWORD}")
    print(f"sandbox api key: {SANDBOX_API_KEY}")


if __name__ == "__main__":
    main()
